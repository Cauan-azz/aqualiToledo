create table if not exists public.ranking (
  id bigint generated by default as identity primary key,
  nome text not null check (char_length(nome) between 1 and 30),
  pontuacao integer not null check (pontuacao between 0 and 10),
  tempo integer not null default 0 check (tempo >= 0),
  criado_em timestamptz not null default now()
);

create table if not exists public.feedbacks (
  id bigint generated by default as identity primary key,
  nome text not null check (char_length(nome) between 1 and 60),
  comentario text not null check (char_length(comentario) between 1 and 500),
  avaliacao integer not null check (avaliacao between 1 and 5),
  aprovado boolean not null default true,
  criado_em timestamptz not null default now()
);

alter table public.ranking enable row level security;
alter table public.feedbacks enable row level security;

-- Ranking: visitantes podem visualizar e inserir resultados.
drop policy if exists "ranking_select_public" on public.ranking;
create policy "ranking_select_public"
on public.ranking for select
to anon, authenticated
using (true);

drop policy if exists "ranking_insert_public" on public.ranking;
create policy "ranking_insert_public"
on public.ranking for insert
to anon, authenticated
with check (
  char_length(nome) between 1 and 30
  and pontuacao between 0 and 10
  and tempo >= 0
);

-- Feedbacks: visitantes podem visualizar apenas aprovados e inserir.
drop policy if exists "feedback_select_approved" on public.feedbacks;
create policy "feedback_select_approved"
on public.feedbacks for select
to anon, authenticated
using (aprovado = true);

drop policy if exists "feedback_insert_public" on public.feedbacks;
create policy "feedback_insert_public"
on public.feedbacks for insert
to anon, authenticated
with check (
  char_length(nome) between 1 and 60
  and char_length(comentario) between 1 and 500
  and avaliacao between 1 and 5
);

-- Índices para carregar os dados rapidamente.
create index if not exists ranking_score_idx
on public.ranking (pontuacao desc, tempo asc, criado_em asc);

create index if not exists feedbacks_date_idx
on public.feedbacks (criado_em desc);
